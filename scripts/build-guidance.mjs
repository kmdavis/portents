#!/usr/bin/env node
/**
 * Turn each content package's `guidance/*.md` into a generated TypeScript module.
 *
 * Guidance is authored as markdown because it is prose, and a diff of prose should
 * look like a diff of prose. But a content pack must stay **pure data with no
 * filesystem access**, or it stops working in a browser -- which is the whole reason
 * `@portent/core` has no `node:fs` in it. So the markdown is the source and a
 * generated module is what ships.
 *
 * Escaping is done with `JSON.stringify`, not template literals: the prose is full of
 * `inline code` spans, and backticks inside a template literal are exactly the kind of
 * thing that works until someone writes a sentence containing `${`.
 *
 * Run with `--check` in CI and in tests to prove the generated files match their
 * markdown. Same pattern as the generated NOTICE files.
 */

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { basename, join } from "node:path";

const PACKAGES = ["content-generic", "content-dnd", "content-pf"];

/**
 * Which system lines each guidance file answers to. Matched by alias, never by guess.
 *
 * **The newer printing claims the bare system name**, so "5e" with no printing gets
 * the 2024 rules and "pf2e" gets the remaster. That is the project's default-to-newer
 * rule expressed as data rather than as a branch, and it is why the older printings
 * list only their explicit forms: a player who says a bare "D&D" should not quietly
 * get the 2014 book.
 */
const ALIASES = {
	generic: ["generic", "generic d20", "d20"],
	"dnd-5e-2024": [
		"5e",
		"dnd",
		"d&d",
		"dnd 5e",
		"d&d 5e",
		"5e (2024)",
		"5e 2024",
		"dnd 5e 2024",
		"d&d 5e 2024",
	],
	"dnd-5e-2014": ["5e (2014)", "5e 2014", "dnd 5e 2014", "d&d 5e 2014"],
	"pf2e-remaster": [
		"pf2e",
		"pathfinder 2e",
		"pf2e (remaster)",
		"pf2e remaster",
		"pathfinder 2e remaster",
	],
	"pf2e-legacy": ["pf2e (legacy)", "pf2e legacy", "pathfinder 2e legacy"],
	pf1e: ["pf1e", "pathfinder 1e"],
};

const check = process.argv.includes("--check");
let problems = 0;

for (const pkg of PACKAGES) {
	const dir = join("packages", pkg, "guidance");
	let files;
	try {
		files = readdirSync(dir).filter((name) => name.endsWith(".md")).sort();
	} catch {
		continue;
	}
	if (files.length === 0) continue;

	const entries = files.map((file) => {
		const id = basename(file, ".md");
		const aliases = ALIASES[id];
		if (!aliases) throw new Error(`No aliases declared for ${pkg}/guidance/${file}. Add them to build-guidance.mjs.`);
		const body = readFileSync(join(dir, file), "utf8").trim();
		if (body.includes("portent_")) {
			throw new Error(
				`${pkg}/guidance/${file} names a portent_* tool. Content packs are consumed by more than ` +
					"one harness and cannot know what their consumer calls things — describe the mechanic instead.",
			);
		}
		return { id, aliases, body };
	});

	const out = [
		"// Generated by scripts/build-guidance.mjs from ../guidance/*.md. Do not edit.",
		"//",
		"// The markdown is the source. Run `pnpm build:guidance` after changing it, or",
		"// `pnpm build:guidance --check` to see whether this file is stale.",
		"",
		'import type { SystemGuidance } from "@portent/core";',
		"",
		"export const guidance: readonly SystemGuidance[] = [",
		...entries.map(
			(entry) =>
				`\t{\n\t\tid: ${JSON.stringify(entry.id)},\n\t\taliases: ${JSON.stringify(entry.aliases)},\n\t\tbody: ${JSON.stringify(entry.body)},\n\t},`,
		),
		"];",
		"",
	].join("\n");

	const target = join("packages", pkg, "src", "guidance.generated.ts");
	if (check) {
		let current = "";
		try {
			current = readFileSync(target, "utf8");
		} catch {
			/* missing counts as stale */
		}
		if (current !== out) {
			console.error(`stale: ${target} — run \`pnpm build:guidance\``);
			problems++;
		}
	} else {
		writeFileSync(target, out);
		console.log(`wrote ${target} (${entries.length} entries)`);
	}
}

if (check && problems > 0) process.exit(1);
if (check) console.log("guidance modules are up to date");
