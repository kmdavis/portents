#!/usr/bin/env node
/** Turn source Markdown resources into browser-safe TypeScript data. */

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

import { parseResourceDocument } from "../../core/src/index.ts";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const source = join(root, "resources");
const output = join(root, "src", "resources.generated.ts");
const check = process.argv.includes("--check");

function markdownFiles(dir) {
	return readdirSync(dir, { withFileTypes: true })
		.flatMap((entry) => {
			const path = join(dir, entry.name);
			return entry.isDirectory() ? markdownFiles(path) : entry.name.endsWith(".md") ? [path] : [];
		})
		.sort();
}

const resources = markdownFiles(source).map((path) => {
	try {
		const resource = parseResourceDocument(readFileSync(path, "utf8"));
		const parts = relative(source, path).split(/[\\/]/);
		if (parts.length !== 2 || parts[0] !== resource.kind) {
			throw new Error(`source path must be resources/<kind>/<slug>.md and match kind ${JSON.stringify(resource.kind)}`);
		}
		return resource;
	} catch (error) {
		const message = error instanceof Error ? error.message : String(error);
		throw new Error(`${relative(root, path)}: ${message}`, { cause: error });
	}
});

const ids = new Set();
for (const resource of resources) {
	if (ids.has(resource.id)) throw new Error(`duplicate resource id ${JSON.stringify(resource.id)}`);
	ids.add(resource.id);
}

const generated = [
	"// Generated by scripts/build-resources.mjs from resources/**/*.md. Do not edit.",
	'import type { ResourceDocument } from "@portents/core";',
	"",
	`export const resources: readonly ResourceDocument[] = ${JSON.stringify(resources, null, "\t")};`,
	"",
].join("\n");

if (check) {
	const current = readFileSync(output, "utf8");
	if (current !== generated) {
		console.error("src/resources.generated.ts is stale; run pnpm build:resources");
		process.exitCode = 1;
	} else {
		console.log(`resources are up to date (${resources.length})`);
	}
} else {
	writeFileSync(output, generated);
	console.log(`wrote ${relative(root, output)} (${resources.length} resources)`);
}
